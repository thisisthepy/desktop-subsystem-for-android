"""Fetches, patches and builds the guest image's default apps (apps.json).

    uv run dsa/apps/apps.py list [--kind gradle]
    uv run dsa/apps/apps.py fetch <app> [--src DIR]
    uv run dsa/apps/apps.py build <app> --out DIR [--src DIR]
    uv run dsa/apps/apps.py patch-tree documentsui --top TREE --android android17 --release cp2a [--lock LOCK]
    uv run dsa/apps/apps.py record documentsui --apk APK --android android17 --out DIR
    uv run dsa/apps/apps.py tree-order [--part services|screens]
    uv run dsa/apps/apps.py tree-apps [--part services|screens]
    uv run dsa/apps/apps.py apk-target permissioncontroller < targets.txt

The system screens (Settings, PermissionController, PackageInstaller, the share sheet) are
AOSP apps built in the same tree as DocumentsUI, at the image's own pins, and stand in place of
the published ones. SettingsLib, which Settings and PermissionController both build from, is a
library of apps.json: patch-tree lays its patches over the tree once, before the apps
(tree-order).

Nothing upstream is kept in this repository. `fetch` clones the pinned commit into
.scratch/apps/<app> (or --src), checks that it is the pinned one, copies DSA's design files
(design/) into the app and applies dsa/apps/<app>/patches/*.patch in order.

The LineageOS apps carry their own Gradle builds, so `build` runs the app's Gradle wrapper
(`assembleRelease`) with no Android tree, against the published SDK and the Maven libraries the
app names. The release APK is unsigned: make-image.py signs it with the image's keys, as it
signs the agent. DocumentsUI is an AOSP app built by Soong only: it compiles against the system
API, its feature flags are generated by aconfig and its resources are chosen by flag, none of
which exists outside an Android tree. So it is built in the whole tree the Framework build's
services job already fetches for services.jar (the published build's own manifest, so
DocumentsUI there is at the commit the image's build was made from): `patch-tree` lays the
design files and patches over packages/apps/DocumentsUI and turns its Material 3 flag on before
that tree is analysed, the job builds the module, and `record` names the APK the way `build`
does.

Each built APK goes to --out under the file name of its place in the image, with
<app>.json beside it: the app, its package, the source commit, and the SHA-256 of every patch
and design file it was built with. make-image.py --default-apps takes that folder.
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
APPS = HERE / "apps.json"
DESIGN = HERE / "design"
SCRATCH = REPO / ".scratch" / "apps"


class AppsError(Exception):
    pass


def load(path=APPS):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def app_entry(name, apps=None):
    """The app (or, for a name in `libraries`, the library of the tree) apps.json names `name`."""
    apps = apps or load()
    for app in apps["apps"] + apps.get("libraries", []):
        if app["name"] == name:
            return app
    raise AppsError(f"apps.json has no app named {name}")


def is_library(app):
    """Whether `app` is a folder of the Android tree that apps build from, not an app."""
    return "kind" not in app["build"]


def libraries(app, apps=None):
    """The libraries of the tree `app` is built from with DSA's patches (SettingsLib)."""
    return [app_entry(name, apps) for name in app.get("libraries", [])]


def pinned_commit(app, android=None):
    """The commit `app` is built from: its one pin, or, for an app pinned per Android version
    (DocumentsUI), the pin of `android`."""
    if "commit" in app:
        return app["commit"]
    commits = app.get("commits", {})
    if android not in commits:
        raise AppsError(f"{app['name']} has no pin for {android}; it has {', '.join(sorted(commits)) or 'none'}")
    return commits[android]


def patches(name):
    """The patches of an app, in the order they apply."""
    return sorted((HERE / name / "patches").glob("*.patch"))


def design_files(app):
    """The design files an app gets, as (source, path inside the app) pairs: the resources, the
    Java helpers, and the preference helper for an app whose settings are a preference list."""
    build = app["build"]
    if "design_files" in app:
        # Only the files named, so that two parts of one APK never carry the same class.
        files = []
        for name in app["design_files"]:
            kind, rest = name.split("/", 1)
            files.append((DESIGN / name, Path(build["res" if kind == "res" else "java"]) / rest))
        return files
    files = [(f, Path(build["res"]) / f.relative_to(DESIGN / "res")) for f in sorted((DESIGN / "res").rglob("*"))
             if f.is_file()]
    files += [(f, Path(build["java"]) / f.relative_to(DESIGN / "java")) for f in sorted((DESIGN / "java").rglob("*"))
              if f.is_file()]
    if build.get("preference"):
        files += [(f, Path(build["java"]) / f.relative_to(DESIGN / "preference"))
                  for f in sorted((DESIGN / "preference").rglob("*")) if f.is_file()]
    return files


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def provenance(app, android=None):
    """What an app is built from: its pin and the SHA-256 of each patch and design file. The
    image check compares this with the repository, so an APK built without DSA's patches, or
    with other ones, is refused."""
    record = {
        "name": app["name"],
        "package": app.get("package"),
        "url": app["url"],
        "commit": pinned_commit(app, android),
        "patches": {p.name: digest(p) for p in patches(app["name"])},
        "design": {str(target.as_posix()): digest(source) for source, target in design_files(app)},
    }
    if app.get("libraries"):
        record["libraries"] = {lib["name"]: provenance(lib, android) for lib in libraries(app)}
    return record


def run(*cmd, cwd=None):
    print("+", " ".join(str(c) for c in cmd), flush=True)
    subprocess.run([str(c) for c in cmd], cwd=cwd, check=True)


def apply_patches(app, src):
    """Copies the design files into `src` and applies the app's patches with GNU patch, which
    works the same whether `src` is a clone of its own or a folder of a larger tree. Each patch
    is tried first, so a patch that no longer applies stops the build before anything changes."""
    src = Path(src)
    for source, target in design_files(app):
        (src / target).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, src / target)
    for patch in patches(app["name"]):
        for check in (["--dry-run"], []):
            run("patch", "-p1", "--forward", "--batch", "--no-backup-if-mismatch", *check,
                "-d", src, "-i", patch)


def fetch(name, src=None):
    """Clones `name` at its pinned commit into `src` (.scratch/apps/<name> by default), checks
    the commit and applies DSA's design files and patches."""
    app = app_entry(name)
    if app["build"]["kind"] != "gradle":
        raise AppsError(f"{name} is built inside the Android tree; use patch-tree")
    src = Path(src) if src else SCRATCH / name
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)
    commit = pinned_commit(app)
    run("git", "init", "-q", src)
    run("git", "-C", src, "fetch", "-q", "--depth", "1", app["url"], commit)
    run("git", "-C", src, "checkout", "-q", "FETCH_HEAD")
    head = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"], check=True,
                          capture_output=True, text=True).stdout.strip()
    if head != commit:
        raise AppsError(f"{name}: fetched {head}, but apps.json pins {commit}")
    apply_patches(app, src)
    return src


def image_file_name(app):
    return Path(app["image"]).name


def write_record(app, apk, out, android=None):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    target = out / image_file_name(app)
    shutil.copyfile(apk, target)
    record = provenance(app, android)
    record["apk"] = target.name
    record["image"] = app["image"]
    (out / f"{app['name']}.json").write_text(json.dumps(record, indent=2) + "\n")
    return target


def release_apk(project):
    """The release APK a Gradle build left in `project` (the app module's folder)."""
    found = sorted((Path(project) / "build/outputs/apk/release").glob("*.apk"))
    if len(found) != 1:
        raise AppsError(f"expected one release APK under {project}/build/outputs/apk/release, found "
                        f"{', '.join(p.name for p in found) or 'none'}")
    return found[0]


def build(name, out, src=None):
    """Builds the release APK of a Gradle app fetched into `src` and records it in `out`."""
    app = app_entry(name)
    if app["build"]["kind"] != "gradle":
        raise AppsError(f"{name} is built inside the Android tree; use patch-tree and record")
    src = Path(src) if src else SCRATCH / name
    module = app["build"]["module"]
    task = f":{module}:assembleRelease" if module else "assembleRelease"
    gradlew = src / "gradlew"
    if os.name != "nt":
        gradlew.chmod(0o755)
    run(gradlew, "--no-daemon", "--stacktrace", task, cwd=src)
    return write_record(app, release_apk(src / module if module else src), out)


def flag_values_text(package, flag):
    return (f'flag_value {{\n  package: "{package}"\n  name: "{flag}"\n'
            "  state: ENABLED\n  permission: READ_ONLY\n}\n")


def set_flags(app, top, release):
    """Turns the app's flags on in the release configuration the tree builds with: one
    <flag>_flag_values.textproto per flag in build/release/aconfig/<release>/<package>/, which
    that folder's Android.bp takes by its *_flag_values.textproto pattern. The published
    Android 16 build has DocumentsUI's Material 3 flag on already; Android 17's does not."""
    flags = app["build"].get("flags")
    if not flags:
        return []
    folder = Path(top) / "build/release/aconfig" / release / flags["package"]
    if not (folder / "Android.bp").is_file():
        raise AppsError(f"{folder} has no Android.bp, so a flag value there would not be read")
    written = []
    for flag in flags["enabled"]:
        path = folder / f"{flag}_flag_values.textproto"
        path.write_text(flag_values_text(flags["package"], flag))
        written.append(path)
    return written


def patch_tree(name, top, android, release, lock=None):
    """Lays the design files and patches of an app built in the Android tree over its folder in
    `top`, after checking that the tree has the pinned commit (when `lock`, the services lock
    the tree was fetched from, is given), and turns its flags on."""
    app = app_entry(name)
    if not is_library(app) and app["build"]["kind"] != "aosp":
        raise AppsError(f"{name} builds with Gradle; use fetch and build")
    commit = pinned_commit(app, android)
    if lock is not None:
        # The manifest project the folder is in: the folder itself, or for a folder inside a
        # larger project (SettingsLib and PackageInstaller are in frameworks/base) that one.
        project = app["build"].get("project", app["build"]["tree_path"])
        tree = json.loads(Path(lock).read_text())
        projects = [p for v in tree["versions"] for p in v["projects"] if p["path"] == project]
        if not projects:
            raise AppsError(f"the tree has no {project}")
        if projects[0]["commit"] != commit:
            raise AppsError(f"the tree has {project} at {projects[0]['commit']}, "
                            f"but apps.json pins {commit} for {android}")
    apply_patches(app, Path(top) / app["build"]["tree_path"])
    if not is_library(app):
        set_flags(app, top, release)


def tree_apps(part=None, apps=None):
    """The apps built in the Android tree, for one part of the Framework build: "services" (the
    default apps built there, DocumentsUI, which go with services.jar), "screens" (the system
    screens, which a runner of their own builds), or every one when `part` is None."""
    apps = apps or load()
    roles = {"services": {"default"}, "screens": {"system"}, None: {"default", "system"}}[part]
    return [a["name"] for a in apps["apps"]
            if a["build"]["kind"] == "aosp" and a.get("role", "default") in roles]


def tree_order(part=None, apps=None):
    """What patch-tree lays over the Android tree for `part` (see tree_apps), in order: the
    libraries those apps build from first, each once, then the apps."""
    apps = apps or load()
    names = tree_apps(part, apps)
    needed = {lib for name in names for lib in app_entry(name, apps).get("libraries", [])}
    return [lib["name"] for lib in apps.get("libraries", []) if lib["name"] in needed] + names


def apk_target(name, targets, apps=None):
    """The ninja target that is the APK of `name`, an app built in the tree inside an APEX
    (PermissionController), whose APK has no install path of its own: the one target of
    `targets` (lines of `ninja -t targets all`) that the first of the app's apk_patterns with any
    match names. The patterns go from the APEX's own variant (named apex<min_sdk>, or after the
    APEX in some Soong versions) to the platform variant, which the module also has
    (apex_available names the platform) and which is built from the same sources."""
    paths = {t.split(": ")[0].strip() for t in targets}
    patterns = app_entry(name, apps)["build"]["apk_patterns"]
    for pattern in patterns:
        found = sorted(p for p in paths if re.search(pattern, p))
        if len(found) > 1:
            raise AppsError(f"expected one APK target of {name} for {pattern}, found {', '.join(found)}")
        if found:
            return found[0]
    raise AppsError(f"the build has no APK target of {name}; looked for {', '.join(patterns)}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    listing = commands.add_parser("list", help="print the apps' names as a JSON list")
    listing.add_argument("--kind", choices=["gradle", "aosp"])
    ordering = commands.add_parser("tree-order", help="print what patch-tree lays over the tree, in order, as a JSON list")
    ordering.add_argument("--part", choices=["services", "screens"])
    in_tree = commands.add_parser("tree-apps", help="print the apps one part of the tree build makes, as a JSON list")
    in_tree.add_argument("--part", choices=["services", "screens"])
    target = commands.add_parser("apk-target", help="pick an APEX app's APK from `ninja -t targets all` on stdin")
    target.add_argument("app")
    fetching = commands.add_parser("fetch", help="clone, check and patch an app")
    fetching.add_argument("app")
    fetching.add_argument("--src", type=Path)
    building = commands.add_parser("build", help="build a fetched Gradle app")
    building.add_argument("app")
    building.add_argument("--src", type=Path)
    building.add_argument("--out", type=Path, required=True)
    tree = commands.add_parser("patch-tree", help="patch an app inside the Android tree")
    tree.add_argument("app")
    tree.add_argument("--top", type=Path, required=True)
    tree.add_argument("--android", required=True)
    tree.add_argument("--release", required=True)
    tree.add_argument("--lock", type=Path)
    recording = commands.add_parser("record", help="record an APK the Android tree built")
    recording.add_argument("app")
    recording.add_argument("--apk", type=Path, required=True)
    recording.add_argument("--android", required=True)
    recording.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        if args.command == "list":
            print(json.dumps([a["name"] for a in load()["apps"]
                              if args.kind is None or a["build"]["kind"] == args.kind]))
        elif args.command == "tree-order":
            print(json.dumps(tree_order(args.part)))
        elif args.command == "tree-apps":
            print(json.dumps(tree_apps(args.part)))
        elif args.command == "apk-target":
            print(apk_target(args.app, sys.stdin.read().splitlines()))
        elif args.command == "fetch":
            print(fetch(args.app, args.src))
        elif args.command == "build":
            print(build(args.app, args.out, args.src))
        elif args.command == "patch-tree":
            patch_tree(args.app, args.top, args.android, args.release, args.lock)
        elif args.command == "record":
            print(write_record(app_entry(args.app), args.apk, args.out, args.android))
    except (AppsError, subprocess.CalledProcessError) as e:
        print(f"apps.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
