//! Generates every language's code for the control protocol from `control.proto`.
//!
//! ```text
//! cd dsa && PROTOC=/path/to/protoc cargo run -p dsa-protocol-codegen
//! ```
//!
//! It writes, under `dsa/protocol/`:
//! - `rust/src/generated/`: the prost types and `schema.rs`;
//! - `java/src/main/java/...`: the protobuf-lite classes and `ControlSchema.java`;
//! - `cpp/generated/`: the protobuf-lite sources and `control_schema.h`;
//! - `schema.sha256`: the schema hash, which every language's tests compare against.
//!
//! CI runs it and fails if the checked-in output differs, so the output always matches the
//! definition. `PROTOC` names the protoc binary; without it, `protoc` on the PATH is used.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use dsa_protocol_schema::{schema_hash, to_hex};

const HEADER: &str =
    "Generated by dsa-protocol-codegen from dsa/protocol/control.proto. Do not edit.";
const JAVA_PACKAGE: &str = "io.github.thisisthepy.dsa.control.v1";

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("dsa-protocol-codegen: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), String> {
    let protocol = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("the codegen crate has no parent folder")?
        .to_path_buf();
    let definition_path = protocol.join("control.proto");
    let definition = fs::read_to_string(&definition_path)
        .map_err(|e| format!("reading {}: {e}", definition_path.display()))?;
    let hash = schema_hash(&definition);
    let hex = to_hex(&hash);
    let protoc = env::var_os("PROTOC")
        .map(PathBuf::from)
        .unwrap_or_else(|| "protoc".into());

    generate_rust(&protocol, &definition_path, &hash, &hex)?;
    generate_java(&protocol, &protoc, &hex)?;
    generate_cpp(&protocol, &protoc, &hex)?;
    write(&protocol.join("schema.sha256"), &format!("{hex}\n"))?;
    println!("schema hash {hex}");
    Ok(())
}

fn write(path: &Path, contents: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("creating {}: {e}", parent.display()))?;
    }
    fs::write(path, contents).map_err(|e| format!("writing {}: {e}", path.display()))
}

/// Empties a folder that holds only generated files, so a removed message leaves nothing behind.
fn reset(dir: &Path) -> Result<(), String> {
    if dir.exists() {
        fs::remove_dir_all(dir).map_err(|e| format!("clearing {}: {e}", dir.display()))?;
    }
    fs::create_dir_all(dir).map_err(|e| format!("creating {}: {e}", dir.display()))
}

fn generate_rust(
    protocol: &Path,
    definition: &Path,
    hash: &[u8; 32],
    hex: &str,
) -> Result<(), String> {
    let out = protocol.join("rust/src/generated");
    reset(&out)?;
    prost_build::Config::new()
        .out_dir(&out)
        .compile_protos(&[definition], &[protocol])
        .map_err(|e| format!("generating the Rust code: {e}"))?;
    let bytes: Vec<String> = hash.iter().map(|b| format!("0x{b:02x}")).collect();
    let schema = format!(
        "// {HEADER}\n\n\
         /// SHA-256 of the normalised control.proto this crate was generated from.\n\
         pub const SCHEMA_HASH: [u8; 32] = [{}];\n\n\
         /// [`SCHEMA_HASH`] in lower-case hexadecimal.\n\
         pub const SCHEMA_HASH_HEX: &str = \"{hex}\";\n",
        bytes.join(", ")
    );
    write(&out.join("schema.rs"), &schema)
}

fn protoc(protoc: &Path, protocol: &Path, out_flag: String) -> Result<(), String> {
    let status = Command::new(protoc)
        .arg(format!("--proto_path={}", protocol.display()))
        .arg(out_flag)
        .arg("control.proto")
        .current_dir(protocol)
        .status()
        .map_err(|e| {
            format!(
                "running {}: {e} (set PROTOC to the protoc binary)",
                protoc.display()
            )
        })?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("{} failed ({status})", protoc.display()))
    }
}

fn generate_java(protocol: &Path, protoc_bin: &Path, hex: &str) -> Result<(), String> {
    let root = protocol.join("java/src/main/java");
    let package_dir = root.join(JAVA_PACKAGE.replace('.', "/"));
    reset(&package_dir)?;
    protoc(
        protoc_bin,
        protocol,
        format!("--java_out=lite:{}", root.display()),
    )?;
    let schema = format!(
        "// {HEADER}\n\n\
         package {JAVA_PACKAGE};\n\n\
         /** The schema hash of the control.proto these classes were generated from. */\n\
         public final class ControlSchema {{\n\
         \x20   private ControlSchema() {{}}\n\n\
         \x20   /** SHA-256 of the normalised definition, in lower-case hexadecimal. */\n\
         \x20   public static final String SCHEMA_HASH_HEX = \"{hex}\";\n\
         }}\n"
    );
    write(&package_dir.join("ControlSchema.java"), &schema)
}

fn generate_cpp(protocol: &Path, protoc_bin: &Path, hex: &str) -> Result<(), String> {
    let out = protocol.join("cpp/generated");
    reset(&out)?;
    protoc(protoc_bin, protocol, format!("--cpp_out={}", out.display()))?;
    let schema = format!(
        "// {HEADER}\n\n\
         #pragma once\n\n\
         namespace dsa::control::v1 {{\n\n\
         // SHA-256 of the normalised control.proto these sources were generated from.\n\
         inline constexpr char kSchemaHashHex[] = \"{hex}\";\n\n\
         }}  // namespace dsa::control::v1\n"
    );
    write(&out.join("control_schema.h"), &schema)
}
